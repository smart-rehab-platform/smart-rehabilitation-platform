function nestFlat(flat) {
  const result = {};
  for (const [keyPath, value] of Object.entries(flat)) {
    const segments = keyPath.split(".");
    let current = result;
    for (let i = 0; i < segments.length - 1; i += 1) {
      current[segments[i]] ??= {};
      current = current[segments[i]];
    }
    current[segments[segments.length - 1]] = value;
  }
  return result;
}

